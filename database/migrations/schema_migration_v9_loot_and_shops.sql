    add column if not exists notes text;

update public.loot_locations
set
    submitted_by = coalesce(
        nullif(trim(submitted_by), ''),
        'Citizen'
    ),
    item_name = coalesce(
        nullif(trim(item_name), ''),
        'Unknown Item'
    ),
    category = coalesce(
        nullif(trim(category), ''),
        'Other'
    ),
    acquisition_type = case
        when acquisition_type in (
            'Looted',
            'Mission Reward',
            'Event Reward',
            'Crafted',
            'Salvaged',
            'Purchased - Special Vendor',
            'Subscriber / Pledge',
            'Other'
        ) then acquisition_type
        else 'Other'
    end,
    system_name = coalesce(
        nullif(trim(system_name), ''),
        'Unknown'
    ),
    location_name = coalesce(
        nullif(trim(location_name), ''),
        'Unknown'
    ),
    rarity = case
        when rarity in (
            'Common',
            'Uncommon',
            'Rare',
            'Very Rare',
            'Event / Limited',
            'Unknown'
        ) then rarity
        else 'Unknown'
    end,
    verification_status = case
        when verification_status in (
            'Verified',
            'Community Report',
            'Needs Recheck',
            'Unverified'
        ) then verification_status
        else 'Unverified'
    end,
    visibility = case
        when visibility in ('Shared', 'Private')
            then visibility
        else 'Shared'
    end;

