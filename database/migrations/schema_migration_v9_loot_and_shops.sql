begin;

create table if not exists public.loot_locations (
    id bigint generated by default as identity primary key,
    user_id uuid not null
        references auth.users(id)
        on delete cascade,
    date_saved timestamptz not null default now(),
    submitted_by text not null default 'Citizen',
    item_name text not null,
    category text not null default 'Other',
    acquisition_type text not null default 'Looted',
    system_name text not null default 'Unknown',
    location_name text not null,
    sub_location text,
    container_type text,
    rarity text not null default 'Unknown',
    mission_or_event text,
    patch_version text,
    verification_status text not null default 'Unverified',
    last_verified date,
    visibility text not null default 'Shared',
    notes text
);

-- Safe repair for partial or older deployments.
alter table public.loot_locations
    add column if not exists user_id uuid
        references auth.users(id)
        on delete cascade;

alter table public.loot_locations
    add column if not exists date_saved timestamptz
        not null default now();

alter table public.loot_locations
    add column if not exists submitted_by text
        not null default 'Citizen';

alter table public.loot_locations
    add column if not exists item_name text;

