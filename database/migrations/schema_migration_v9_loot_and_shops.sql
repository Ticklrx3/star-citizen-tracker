drop policy if exists
    "Authenticated users can read visible loot entries"
on public.loot_locations;

drop policy if exists
    "Users can insert own loot entries"
on public.loot_locations;

drop policy if exists
    "Users can update own loot entries"
on public.loot_locations;

drop policy if exists
    "Users can delete own loot entries"
on public.loot_locations;

-- Shared records can be read by every authenticated app user.
-- Private records can only be read by their creator.
create policy
    "Authenticated users can read visible loot entries"
on public.loot_locations
for select
to authenticated
using (
    visibility = 'Shared'
    or auth.uid() = user_id
);

create policy
    "Users can insert own loot entries"
on public.loot_locations
for insert
to authenticated
with check (auth.uid() = user_id);

create policy
    "Users can update own loot entries"
on public.loot_locations
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy
    "Users can delete own loot entries"
on public.loot_locations
for delete
to authenticated
using (auth.uid() = user_id);

commit;

notify pgrst, 'reload schema';
select pg_notify('pgrst', 'reload schema');

select
    count(*) as loot_entries,
    count(*) filter (
        where visibility = 'Shared'
    ) as shared_entries,
    count(*) filter (
        where visibility = 'Private'
    ) as private_entries,
    count(*) filter (
        where verification_status = 'Verified'
    ) as verified_entries
from public.loot_locations;
