select
    count(*) as commodity_records,
    coalesce(sum(total_value), 0) as verified_cargo_value,
    coalesce(sum(cash_effect), 0) as net_cash_effect,
    count(*) filter (
        where quantity_scu <= 0 or unit_price <= 0
    ) as incomplete_math_rows
from public.commodity_transactions;
