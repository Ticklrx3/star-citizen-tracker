-- Star Citizen Tracker
-- Blueprint Tracker repair migration
-- Run this entire file once in Supabase SQL Editor.

begin;

create table if not exists public.blueprint_tracker (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    date_saved timestamptz not null default now(),
    blueprint_name text not null,
    blueprint_category text not null default 'Other',
    blueprint_status text not null default 'Owned',
    source_location text,
    copies_owned integer not null default 1,
    target_builds integer not null default 1,
    materials jsonb not null default '{}'::jsonb,
    notes text
);

-- Repair partially created tables from an earlier migration.
alter table public.blueprint_tracker
    add column if not exists user_id uuid references auth.users(id) on delete cascade;

alter table public.blueprint_tracker
    add column if not exists date_saved timestamptz not null default now();

alter table public.blueprint_tracker
    add column if not exists blueprint_name text;

alter table public.blueprint_tracker
    add column if not exists blueprint_category text not null default 'Other';

alter table public.blueprint_tracker
    add column if not exists blueprint_status text not null default 'Owned';

alter table public.blueprint_tracker
    add column if not exists source_location text;

alter table public.blueprint_tracker
    add column if not exists copies_owned integer not null default 1;

alter table public.blueprint_tracker
    add column if not exists target_builds integer not null default 1;

alter table public.blueprint_tracker
    add column if not exists materials jsonb not null default '{}'::jsonb;

alter table public.blueprint_tracker
    add column if not exists notes text;

update public.blueprint_tracker
set copies_owned = 1
where copies_owned is null or copies_owned < 1;

update public.blueprint_tracker
set target_builds = 1
where target_builds is null or target_builds < 1;

update public.blueprint_tracker
set materials = '{}'::jsonb
where materials is null;

alter table public.blueprint_tracker
    drop constraint if exists blueprint_tracker_copies_owned_check;

alter table public.blueprint_tracker
    add constraint blueprint_tracker_copies_owned_check
    check (copies_owned >= 1);

alter table public.blueprint_tracker
    drop constraint if exists blueprint_tracker_target_builds_check;

alter table public.blueprint_tracker
    add constraint blueprint_tracker_target_builds_check
    check (target_builds >= 1);

create index if not exists blueprint_tracker_user_id_idx
    on public.blueprint_tracker(user_id);

create index if not exists blueprint_tracker_date_saved_idx
    on public.blueprint_tracker(date_saved desc);

alter table public.blueprint_tracker enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete
    on table public.blueprint_tracker
    to authenticated;

do $$
begin
    if to_regclass('public.blueprint_tracker_id_seq') is not null then
        execute 'grant usage, select on sequence public.blueprint_tracker_id_seq to authenticated';
    end if;
end
$$;

drop policy if exists "Users can read own blueprints"
on public.blueprint_tracker;

drop policy if exists "Users can insert own blueprints"
on public.blueprint_tracker;

drop policy if exists "Users can update own blueprints"
on public.blueprint_tracker;

drop policy if exists "Users can delete own blueprints"
on public.blueprint_tracker;

create policy "Users can read own blueprints"
on public.blueprint_tracker
for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can insert own blueprints"
on public.blueprint_tracker
for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can update own blueprints"
on public.blueprint_tracker
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users can delete own blueprints"
on public.blueprint_tracker
for delete
to authenticated
using (auth.uid() = user_id);

commit;

-- Refresh the Supabase REST schema cache.
notify pgrst, 'reload schema';

-- Verification result. It should return one row with table_ready = true.
select
    to_regclass('public.blueprint_tracker') is not null as table_ready,
    has_table_privilege(
        'authenticated',
        'public.blueprint_tracker',
        'select,insert,update,delete'
    ) as authenticated_permissions_ready;
